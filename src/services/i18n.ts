// Storage helper functions
export function getLanguage(): AppLanguage {
  if (typeof window === 'undefined') return 'en';
  const stored = db.getState().settings.language;
  return stored === 'fr' || stored === 'ar' || stored === 'en' ? stored : 'en';
}

export function setLanguage(lang: AppLanguage, persist: boolean = true): void {
  if (typeof document === 'undefined') return;

  const validLang: AppLanguage = lang === 'fr' || lang === 'ar' || lang === 'en' ? lang : 'en';
  const isRtl = validLang === 'ar';

  // Apply HTML document attributes for direction & language
  document.documentElement.lang = validLang;
  document.documentElement.dir = isRtl ? 'rtl' : 'ltr';

  if (isRtl) {
    document.documentElement.classList.add('rtl');
  } else {
    document.documentElement.classList.remove('rtl');
  }

  if (persist) {
    db.updateState(s => {
      s.settings.language = validLang;
    });
  }

  // Broadcast change to React components
  window.dispatchEvent(new CustomEvent('app_language_changed', { detail: { language: validLang, isRtl } }));
}

export function initLanguage(): void {
  const current = getLanguage();
  setLanguage(current, false);
}

// Translation key resolver: supports nested paths like 'nav.dashboard'
export function t(keyPath: string, fallback?: string): string {
  const lang = getLanguage();
  const dict = translations[lang] || translations.en;
  const enDict = translations.en;

  const resolve = (obj: any, path: string): string | undefined => {
    return path.split('.').reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj);
  };

  const localizedValue = resolve(dict, keyPath);
  if (localizedValue !== undefined) return localizedValue;

  const fallbackEnValue = resolve(enDict, keyPath);
  if (fallbackEnValue !== undefined) return fallbackEnValue;

  return fallback || keyPath;
}

// React Hook for dynamic re-render on language change
export function useTranslation() {
  const [currentLang, setCurrentLang] = useState<AppLanguage>(getLanguage());

  useEffect(() => {
    const handleLangChange = (e: any) => {
      const newLang = e?.detail?.language || getLanguage();
      setCurrentLang(newLang);
    };

    window.addEventListener('app_language_changed', handleLangChange);
    return () => {
      window.removeEventListener('app_language_changed', handleLangChange);
    };
  }, []);

  return {
    t: (keyPath: string, fallback?: string) => t(keyPath, fallback),
    language: currentLang,
    isRtl: currentLang === 'ar',
    setLanguage: (lang: AppLanguage) => setLanguage(lang, true),
  };
}
